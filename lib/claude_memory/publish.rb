# frozen_string_literal: true

require "digest"
require "fileutils"

module ClaudeMemory
  # Generates Markdown snapshots from active facts for use as project memory.
  # Publishes to .claude/rules/ (shared), a local file, or the home directory.
  class Publish
    RULES_DIR = ".claude/rules"
    GENERATED_FILE = "claude_memory.generated.md"
    OBSERVATIONS_FILE = "claude_memory.observations.md"
    MAX_PUBLISHED_OBSERVATIONS = 50

    # @param store [Store::SQLiteStore] database store for reading facts
    # @param file_system [Infrastructure::FileSystem] filesystem abstraction for I/O
    def initialize(store, file_system: Infrastructure::FileSystem.new)
      @store = store
      @fs = file_system
    end

    # Generate a complete Markdown snapshot with header and body
    # @param since [String, nil] ISO 8601 timestamp to include recent supersessions
    # @return [String] full Markdown document
    def generate_snapshot(since: nil)
      header = <<~HEADER
        <!--
          This file is auto-generated by claude-memory.
          Do not edit manually - changes will be overwritten.
          Generated: #{Time.now.utc.iso8601}
        -->

        # Project Memory

      HEADER

      header + generate_body(since: since)
    end

    # Write snapshot to disk if content has changed
    # @param mode [Symbol] output target (:shared, :local, or :home)
    # @param granularity [Symbol] snapshot granularity (currently only :repo)
    # @param since [String, nil] ISO 8601 timestamp for recent supersessions
    # @param rules_dir [String, nil] override rules directory path
    # @return [Hash] result with :status (:updated or :unchanged) and :path
    def publish!(mode: :shared, granularity: :repo, since: nil, rules_dir: nil)
      path = output_path(mode, rules_dir: rules_dir)
      body = generate_body(since: since)

      result = if should_write?(path, body)
        content = generate_snapshot(since: since)
        @fs.write(path, content)
        ensure_import_exists(mode, path, rules_dir: rules_dir)
        {status: :updated, path: path}
      else
        {status: :unchanged, path: path}
      end

      # The episodic observation log is published as a sibling artifact, not
      # imported into CLAUDE.md — it reaches the session via the SessionStart
      # context hook (Block 1). The file is a durable, diff-able snapshot.
      publish_observations!(mode: mode, rules_dir: rules_dir)

      result
    end

    # Write the episodic observation log to .claude/rules/ when there are
    # observations to show. Mirrors publish!'s change-detection so the file is
    # only rewritten when its body changes.
    #
    # @return [Hash] :status (:updated, :unchanged, or :empty) and :path
    def publish_observations!(mode: :shared, rules_dir: nil)
      body = observations_body
      path = observations_path(mode, rules_dir: rules_dir)
      return {status: :empty, path: path} if body.nil?

      if should_write?(path, body)
        @fs.write(path, observations_snapshot(body))
        {status: :updated, path: path}
      else
        {status: :unchanged, path: path}
      end
    end

    private

    def observations_path(mode, rules_dir: nil)
      dir = if mode == :home
        File.join(Dir.home, ".claude", "claude_memory")
      else
        rules_dir || RULES_DIR
      end
      File.join(dir, OBSERVATIONS_FILE)
    end

    def observations_body
      rows = @store.recent_observations(limit: MAX_PUBLISHED_OBSERVATIONS)
      Observe::ObservationsRenderer.render(rows, title: "Project Observations")
    end

    def observations_snapshot(body)
      <<~HEADER + body
        <!--
          This file is auto-generated by claude-memory.
          Do not edit manually - changes will be overwritten.
          Generated: #{Time.now.utc.iso8601}
        -->

      HEADER
    end

    def output_path(mode, rules_dir: nil)
      case mode
      when :shared
        dir = rules_dir || RULES_DIR
        File.join(dir, GENERATED_FILE)
      when :local
        ".claude_memory.local.md"
      when :home
        project_name = File.basename(Dir.pwd)
        File.join(Dir.home, ".claude", "claude_memory", "#{project_name}.md")
      else
        dir = rules_dir || RULES_DIR
        File.join(dir, GENERATED_FILE)
      end
    end

    def fetch_active_facts
      @store.facts
        .left_join(:entities, id: :subject_entity_id)
        .select(
          Sequel[:facts][:id],
          Sequel[:facts][:predicate],
          Sequel[:facts][:object_literal],
          Sequel[:facts][:status],
          Sequel[:facts][:confidence],
          Sequel[:facts][:created_at],
          Sequel[:entities][:canonical_name].as(:subject_name)
        )
        .where(Sequel[:facts][:status] => "active")
        .order(Sequel.desc(Sequel[:facts][:created_at]))
        .limit(100)
        .all
    end

    def fetch_recent_supersessions(since)
      return [] unless since

      @store.facts
        .left_join(:entities, id: :subject_entity_id)
        .select(
          Sequel[:facts][:id],
          Sequel[:facts][:predicate],
          Sequel[:facts][:object_literal],
          Sequel[:facts][:valid_to],
          Sequel[:entities][:canonical_name].as(:subject_name)
        )
        .where(Sequel[:facts][:status] => "superseded")
        .where { Sequel[:facts][:valid_to] >= since }
        .order(Sequel.desc(Sequel[:facts][:valid_to]))
        .limit(20)
        .all
    end

    # @return [String] Markdown section for decision facts
    def generate_decisions_section(facts)
      generate_section(facts, section: :decisions, title: "Current Decisions") do |d|
        "- #{d[:object_literal]}"
      end
    end

    # @return [String] Markdown section for convention facts
    def generate_conventions_section(facts)
      generate_section(facts, section: :conventions, title: "Conventions") do |c|
        "- #{c[:object_literal]}"
      end
    end

    # @return [String] Markdown section for technical constraint facts
    def generate_constraints_section(facts)
      generate_section(facts, section: :constraints, title: "Technical Constraints") do |c|
        "- **#{humanize(c[:predicate])}**: #{c[:object_literal]}"
      end
    end

    def generate_section(facts, section:, title:, &row_formatter)
      rows = facts.select { |f| Resolve::PredicatePolicy.section_for(f[:predicate]) == section }
      return "" if rows.empty?

      (["## #{title}\n"] + rows.map(&row_formatter)).join("\n") + "\n"
    end

    # @return [String] Markdown section for additional knowledge grouped by predicate
    def generate_additional_section(facts)
      additional = facts.select { |f| Resolve::PredicatePolicy.section_for(f[:predicate]) == :additional }
      return "" if additional.empty?

      grouped = additional.group_by { |f| f[:predicate] }
      lines = ["## Additional Knowledge\n"]
      grouped.each do |predicate, group_facts|
        lines << "### #{humanize(predicate)}\n"
        group_facts.each do |f|
          subject = f[:subject_name] || "repo"
          lines << "- #{subject}: #{f[:object_literal]}"
        end
        lines << ""
      end
      lines.join("\n") + "\n"
    end

    # @return [String] Markdown section for open conflicts
    def generate_conflicts_section(conflicts)
      return "" if conflicts.empty?

      lines = ["## Open Conflicts\n"]
      lines << "The following facts are in conflict and need resolution:\n"
      conflicts.each do |c|
        lines << "- Conflict ##{c[:id]}: Fact #{c[:fact_a_id]} vs Fact #{c[:fact_b_id]}"
      end
      lines.join("\n") + "\n"
    end

    # @return [String] Markdown section for recently superseded facts
    def generate_supersessions_section(supersessions)
      return "" if supersessions.empty?

      lines = ["## Recent Changes\n"]
      supersessions.each do |s|
        lines << "- [Superseded] #{s[:subject_name]}.#{s[:predicate]}: #{s[:object_literal]} (until #{s[:valid_to]})"
      end
      lines.join("\n") + "\n"
    end

    def generate_body(since: nil)
      facts = fetch_active_facts
      conflicts = @store.open_conflicts
      recent_supersessions = fetch_recent_supersessions(since)

      sections = []
      sections << generate_decisions_section(facts)
      sections << generate_conventions_section(facts)
      sections << generate_constraints_section(facts)
      sections << generate_additional_section(facts)
      sections << generate_conflicts_section(conflicts) if conflicts.any?
      sections << generate_supersessions_section(recent_supersessions) if recent_supersessions.any?

      sections.compact.reject(&:empty?).join("\n")
    end

    def should_write?(path, new_body)
      return true unless @fs.exist?(path)

      existing_body = extract_body(@fs.read(path))
      existing_body != new_body
    end

    def extract_body(content)
      # Strip the HTML comment header and "# Project Memory" heading
      content
        .sub(/\A<!--.*?-->\s*/m, "")
        .sub(/\A# Project Memory\s*/m, "")
    end

    def ensure_import_exists(mode, path, rules_dir: nil)
      return if mode == :local

      # Determine CLAUDE.md location based on rules_dir
      claude_md = if rules_dir
        # If rules_dir is provided (e.g., /tmp/xyz/.claude/rules),
        # CLAUDE.md should be in parent dir (e.g., /tmp/xyz/.claude/CLAUDE.md)
        File.join(File.dirname(rules_dir), "CLAUDE.md")
      else
        ".claude/CLAUDE.md"
      end

      import_line = case mode
      when :shared
        dir = rules_dir || RULES_DIR
        "@#{dir}/#{GENERATED_FILE}"
      when :home
        "@~/#{path.sub(Dir.home + "/", "")}"
      else
        "@#{path}"
      end

      if @fs.exist?(claude_md)
        content = @fs.read(claude_md)
        return if content.include?(import_line)

        @fs.write(claude_md, content + "\n#{import_line}\n")
      else
        @fs.write(claude_md, "# Project Memory\n\n#{import_line}\n")
      end
    end

    def humanize(predicate)
      predicate.tr("_", " ").capitalize
    end
  end
end
